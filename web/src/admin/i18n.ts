export function permLabel(t: AdminStrings, key: string): string {
  const k = PERM_LABEL_KEY[key]
  return k ? t[k] : key
}

export function fmt(template: string, ...args: (string | number)[]): string {
  let i = 0
  return template.replace(/%[sd]/g, () => String(args[i++] ?? ''))
}
